// ---------------------------------------------------------------------------
// Resources — db/030, db/031. The first files this product stores.
// ---------------------------------------------------------------------------

export type ResourceCategory = 'video' | 'handout' | 'aac_board' | 'other'

export type ResourceShare = {
  id: string
  student_id: string
  students: { first_name: string; last_name: string } | null
  resource_acknowledgements: { profile_id: string; acknowledged_at: string }[]
}

export type ResourceRow = {
  id: string
  owner_id: string | null
  title: string
  description: string | null
  category: ResourceCategory
  storage_path: string | null
  mime_type: string | null
  size_bytes: number | null
  created_at: string
  resource_shares: ResourceShare[]
}

/** The bucket enforces these on the server. Checking here only buys a better message. */
export const RESOURCE_MAX_BYTES = 52_428_800 // 50 MB — must match db/030
export const RESOURCE_MIME_TYPES = [
  'application/pdf',
  'image/png',
  'image/jpeg',
  'image/webp',
  'video/mp4',
  'video/quicktime',
  'audio/mpeg',
  'audio/mp4',
]

/**
 * Everything the signed-in person may see.
 *
 * No filter, as everywhere else here. A specialist gets what they uploaded, a
 * teacher and a family get what has been shared with a child they are entitled
 * to, and a school administrator gets their school's. All of that is decided by
 * `can_view_resource()` in db/030, not by this query.
 */
export async function fetchResources(): Promise<ResourceRow[]> {
  const { data, error } = await supabase
    .from('resources')
    .select(
      `id, owner_id, title, description, category, storage_path, mime_type,
       size_bytes, created_at,
       resource_shares ( id, student_id,
                         students ( first_name, last_name ),
                         resource_acknowledgements ( profile_id, acknowledged_at ) )`,
    )
    .order('created_at', { ascending: false })

  if (error) throw new Error(error.message)

  /**
   * NORMALISED RATHER THAN CAST.
   *
   * PostgREST returns an object for a many-to-one embed and an array for a
   * many-to-many one, and the client's inferred type here says array while the
   * relationship (many shares → one student) makes it an object. Forcing the
   * cast would compile and then quietly render "a student you cannot see" for
   * every row if the guess were wrong — a silent wrong answer rather than an
   * error. Accepting both shapes costs three lines and cannot be wrong.
   */
  type RawShare = Omit<ResourceShare, 'students'> & {
    students: ResourceShare['students'] | ResourceShare['students'][]
  }
  type RawResource = Omit<ResourceRow, 'resource_shares'> & {
    resource_shares: RawShare[]
  }

  const rows = (data ?? []) as unknown as RawResource[]

  return rows
    // A row whose upload never finished is a failed upload, not a resource.
    // Filtered here rather than in each screen so none of them can forget.
    .filter((r) => r.storage_path !== null)
    .map((r) => ({
      ...r,
      resource_shares: (r.resource_shares ?? []).map((s) => ({
        ...s,
        students: Array.isArray(s.students) ? (s.students[0] ?? null) : s.students,
      })),
    }))
}

/** Storage keys are safer without spaces and accents; the extension is kept. */
function safeFileName(name: string): string {
  const cleaned = name.normalize('NFKD').replace(/[^a-zA-Z0-9._-]/g, '_')
  return cleaned.replace(/^_+/, '').slice(-120) || 'file'
}

/**
 * Create the row, put the file in the bucket, then record where it went.
 *
 * THREE STEPS AND THEY CAN FAIL SEPARATELY. The row has to exist first because
 * its id IS the folder name — that is what lets the storage policies decide
 * access by looking the resource up, instead of a second set of rules that can
 * disagree with the first.
 *
 * If the upload fails, the row is deleted rather than left behind. An empty
 * resource in a list is worse than a failed upload the person can retry.
 */
export async function uploadResource(input: {
  schoolId: string
  ownerId: string
  title: string
  description: string | null
  category: ResourceCategory
  file: File
}): Promise<void> {
  if (input.file.size > RESOURCE_MAX_BYTES) {
    throw new Error(
      `That file is ${formatBytes(input.file.size)}. The limit is ${formatBytes(RESOURCE_MAX_BYTES)}.`,
    )
  }
  if (!RESOURCE_MIME_TYPES.includes(input.file.type)) {
    throw new Error(
      `${input.file.type || 'That file type'} is not accepted. Use a PDF, an image, an MP4 or an audio file.`,
    )
  }

  const { data: row, error: insertError } = await supabase
    .from('resources')
    .insert({
      school_id: input.schoolId,
      owner_id: input.ownerId,
      title: input.title,
      description: input.description,
      category: input.category,
    })
    .select('id')
    .single()

  if (insertError) throw new Error(insertError.message)

  const path = `${row.id}/${safeFileName(input.file.name)}`

  const { error: uploadError } = await supabase.storage
    .from('resources')
    .upload(path, input.file, { contentType: input.file.type, upsert: false })

  if (uploadError) {
    await supabase.from('resources').delete().eq('id', row.id)
    throw new Error(`The file could not be uploaded: ${uploadError.message}`)
  }

  const { data: updated, error: updateError } = await supabase
    .from('resources')
    .update({
      storage_path: path,
      mime_type: input.file.type,
      size_bytes: input.file.size,
    })
    .eq('id', row.id)
    .select('id')

  if (updateError) throw new Error(updateError.message)
  assertChanged(updated, 'The resource')
}

/**
 * A link to the file that expires.
 *
 * The bucket is private, so there is no permanent URL to hand out. Supabase
 * mints this only if the storage policies would let this person read the
 * object, which means the link cannot be obtained by someone who should not
 * have it — and it stops working shortly after, so a forwarded one is not a
 * lasting hole.
 */
export async function resourceDownloadUrl(storagePath: string): Promise<string> {
  const { data, error } = await supabase.storage
    .from('resources')
    .createSignedUrl(storagePath, 120)

  if (error) throw new Error(error.message)
  return data.signedUrl
}

