/**
 * Create students, reporting per row.
 *
 * CHUNKED, THEN ROW BY ROW ON FAILURE. A single insert of 600 rows is one
 * request and fails entirely if row 412 is bad — losing 599 good records to one
 * typo. One request per row never does that but is 600 round trips on a school
 * laptop. So it inserts in chunks, and only if a chunk is refused does it retry
 * that chunk one at a time to find which row was the problem. Fast in the
 * ordinary case, precise in the bad one.
 *
 * `schoolId` IS SENT, AND THE DATABASE STILL DECIDES. An earlier version of
 * this omitted it on the reasoning that the column would default to the
 * caller's school. It does not: `students.school_id` is `not null` with no
 * default (db/002), so every insert was refused — RLS reporting "Your account
 * cannot add students to this school" to a school administrator adding students
 * to their own school. The claim in this comment was never checked, and only
 * pressing the button in a browser found it.
 *
 * Sending it is safe because the policy in db/004 requires
 * `school_id = my_school_id()`. A browser that tampers with the value is
 * refused by the database, so this is a convenience for the caller and not a
 * decision the client gets to make.
 */
export async function createStudents(
  rows: NewStudent[],
  schoolId: string,
): Promise<ImportOutcome> {
  const CHUNK = 100
  const outcome: ImportOutcome = { created: 0, failed: [] }

  const toRecord = (r: NewStudent) => ({
    school_id: schoolId,
    first_name: r.first_name,
    last_name: r.last_name,
    year_level: r.year_level,
    external_ref: r.external_ref,
    date_of_birth: r.date_of_birth,
  })

  for (let i = 0; i < rows.length; i += CHUNK) {
    const chunk = rows.slice(i, i + CHUNK)
    const { error } = await supabase.from('students').insert(chunk.map(toRecord))

    if (!error) {
      outcome.created += chunk.length
      continue
    }

    // Something in this chunk was refused. Find out what, one at a time.
    for (const row of chunk) {
      const { error: rowError } = await supabase
        .from('students')
        .insert(toRecord(row))
      if (rowError) {
        outcome.failed.push({
          line: row.line,
          name: `${row.first_name} ${row.last_name}`.trim(),
          reason: explainInsertError(rowError.message),
        })
      } else {
        outcome.created += 1
      }
    }
  }

  return outcome
}

/** Postgres speaks to itself; this says the same thing to a school office. */
function explainInsertError(message: string): string {
  if (/duplicate key|unique/i.test(message))
    return 'That student ID is already on the roll.'
  if (/row-level security/i.test(message))
    return 'Your account cannot add students to this school.'
  if (/invalid input syntax for type date/i.test(message))
    return 'The date of birth could not be read.'
  return message.slice(0, 160)
}

