/**
 * How many rows sit behind each tab of a triage queue.
 *
 * WHY THIS EXISTS. Both queues open on their "new" tab, and both showed
 * "Nothing waiting" while rows sat one tab away. Somebody looked at that and
 * reasonably concluded the feature was broken — the screen was telling the
 * truth about the tab and looked like it was telling the truth about the
 * system.
 *
 * Counted in the database with `head: true`, not by fetching rows and measuring
 * the array. PostgREST stops at a thousand without saying so, and a tab reading
 * "1000" when there are four thousand is the fault this project has produced
 * nine times.
 *
 * IT THROWS RATHER THAN RETURNING ZEROS. A count that could not be taken must
 * not render as 0 — the tab shows no number at all instead, which is the
 * difference between "none" and "unknown".
 */
export async function fetchQueueCounts(
  table: 'enquiries' | 'specialist_applications',
  statuses: readonly string[],
): Promise<Record<string, number>> {
  const results = await Promise.all([
    supabase.from(table).select('id', { count: 'exact', head: true }),
    ...statuses.map((status) =>
      supabase
        .from(table)
        .select('id', { count: 'exact', head: true })
        .eq('status', status),
    ),
  ])

  const failed = results.find((r) => r.error)
  if (failed?.error) throw new Error(failed.error.message)

  return Object.fromEntries([
    ['all', results[0].count ?? 0],
    ...statuses.map((status, i) => [status, results[i + 1].count ?? 0]),
  ])
}

