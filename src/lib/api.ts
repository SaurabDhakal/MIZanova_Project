/**
 * Register an IEP document against a student.
 *
 * The file is optional. A school that has not got the PDF to hand can still
 * register that the plan exists so the family knows and can confirm reading it
 * — which is what this table did on its own from db/008 until db/034 gave it a
 * bucket.
 */
export const IEP_MAX_BYTES = 20_971_520 // 20 MB — must match db/034
export const IEP_MIME_TYPES = [
  'application/pdf',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'image/png',
  'image/jpeg',
]

export async function createIepDocument(input: {
  studentId: string
  name: string
  documentDate: string
  notes: string
  file?: File | null
}): Promise<void> {
  if (input.file) {
    if (input.file.size > IEP_MAX_BYTES) {
      throw new Error(
        `That file is ${formatBytes(input.file.size)}. The limit is ${formatBytes(IEP_MAX_BYTES)}.`,
      )
    }
    if (!IEP_MIME_TYPES.includes(input.file.type)) {
      throw new Error(
        `${input.file.type || 'That file type'} is not accepted. Use a PDF, a Word document or an image.`,
      )
    }
  }

  const { data: session } = await supabase.auth.getUser()

  // The row first, because its id is the folder name — the same convention as
  // resources, and what lets the storage policies decide by looking the
  // document up rather than running a second set of rules beside this one.
  const { data: row, error } = await supabase
    .from('iep_documents')
    .insert({
      student_id: input.studentId,
      name: input.name.trim(),
      document_date: input.documentDate,
      notes: input.notes.trim() === '' ? null : input.notes.trim(),
      created_by: session.user?.id ?? null,
    })
    .select('id')
    .single()

  if (error) throw new Error(error.message)
  if (!input.file) return

  const path = `${row.id}/${safeFileName(input.file.name)}`
  const { error: uploadError } = await supabase.storage
    .from('iep-documents')
    .upload(path, input.file, { contentType: input.file.type, upsert: false })

  if (uploadError) {
    /**
     * The register entry SURVIVES a failed upload here, unlike a resource.
     *
     * A resource with no file is nothing. A registered IEP with no file is
     * exactly what this table was for its first six scripts — the family still
     * learns the plan exists and can still confirm reading it. Throwing away
     * the record because the network dropped would lose the more useful half.
     */
    throw new Error(
      `The document was registered, but the file could not be uploaded: ${uploadError.message}. Attach it again from the document below.`,
    )
  }

  const { data: updated, error: updateError } = await supabase
    .from('iep_documents')
    .update({ storage_path: path })
    .eq('id', row.id)
    .select('id')

  if (updateError) throw new Error(updateError.message)
  assertChanged(updated, 'The document')
}

