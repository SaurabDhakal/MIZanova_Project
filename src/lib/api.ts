export async function createSession(input: {
  studentId: string
  sessionDate: string
  durationMinutes: number
  goalId: string | null
  trialsSuccessful: number | null
  trialsTotal: number | null
  clinicalNotes: string
  sharedSummary: string
  shareWithTeacher: boolean
  shareWithParents: boolean
  /** Returns the new session's id, so an appointment can point at it. */
}): Promise<string> {
  const { data: user } = await supabase.auth.getUser()
  const specialistId = user.user?.id
  if (!specialistId) throw new Error('You are not signed in.')

  const { data: session, error } = await supabase
    .from('specialist_sessions')
    .insert({
      student_id: input.studentId,
      specialist_id: specialistId,
      session_date: input.sessionDate,
      duration_minutes: input.durationMinutes,
      goal_id: input.goalId,
      trials_successful: input.trialsSuccessful,
      trials_total: input.trialsTotal,
      shared_summary: input.sharedSummary.trim() || null,
      shared_with_teacher: input.shareWithTeacher,
      shared_with_parents: input.shareWithParents,
    })
    .select('id')
    .single()

  if (error) throw new Error(error.message)

  // Second write, second table. If it fails the session still exists without
  // its notes, which is recoverable — the specialist can add them. The reverse
  // is not: notes with no session to belong to.
  if (input.clinicalNotes.trim() !== '') {
    const { error: notesError } = await supabase
      .from('specialist_session_notes')
      .insert({ session_id: session.id, notes: input.clinicalNotes.trim() })

    if (notesError) {
      throw new Error(
        `The session was saved but your clinical notes were not: ${notesError.message}. Open the session and add them again.`,
      )
    }
  }

  return session.id
}

