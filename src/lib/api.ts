/**
 * Turn a zero-row update into a visible error.
 *
 * A Supabase `update` whose rows are filtered out by Row-Level Security does
 * NOT fail: it returns success, having changed nothing. Every mutation that
 * relies on a policy therefore has to check how many rows it actually touched,
 * or a refusal is indistinguishable from a button that does nothing.
 *
 * This has already cost real debugging time in this project, twice.
 */
function assertChanged(
  rows: unknown[] | null,
  what: string,
): void {
  if (!rows || rows.length === 0) {
    throw new Error(
      `${what} was not saved. The database refused the change — usually that means your account does not have permission for this record. Try signing out and back in; if it persists, the assignment behind it is probably missing.`,
    )
  }
}

/**
 * One page of a list, and how many there really are.
 *
 * WHY THIS TYPE EXISTS. PostgREST returns at most 1000 rows and says nothing
 * about it. A screen asking for every staff member at two hundred schools gets
 * a thousand of thirteen thousand, renders them, and looks complete — which is
 * the same fault as a check that passes when it could not check, wearing a
 * different hat. This project has now found that shape six times.
 *
 * `total` comes from the database with `count: 'exact'`, so "showing 50 of
 * 13,204" is a fact rather than an inference from the length of an array.
 *
 * The count costs a second scan on every page. That is worth paying: the
 * alternative is a number nobody can trust, and a list that quietly stops.
 */
export type Page<T> = {
  rows: T[]
  /** Every row matching the filter, not just the ones fetched. */
  total: number
  /** Zero-based. */
  page: number
  pageSize: number
  hasMore: boolean
}

export const PAGE_SIZE = 50

/** Turns a Supabase response into a Page, so no screen counts rows itself. */
function toPage<T>(
  rows: T[] | null,
  count: number | null,
  page: number,
  pageSize: number,
): Page<T> {
  const total = count ?? 0
  return {
    rows: rows ?? [],
    total,
    page,
    pageSize,
    hasMore: (page + 1) * pageSize < total,
  }
}

/**
 * Every database read the application makes, in one place.
 *
 * Screens call these; screens never build queries themselves. Two reasons:
 * a query written inline in a component gets copy-pasted and drifts, and when
 * a column is renamed you want one file to fix, not twelve.
 *
 * None of these functions check permissions. That is not an oversight — Row-
 * Level Security decides what comes back. A query for every student in the
 * country returns only the students you are entitled to. If a screen looks
 * empty, the honest question is "should this person see anything?", not
 * "which filter did I forget?".
 */

export type StudentRow = {
  id: string
  first_name: string
  last_name: string
  /** Generated by Postgres: "Ethan M." — the only name a parent may see. */
  display_name: string
  year_level: string | null
  external_ref: string | null
  is_active: boolean
}

/**
 * Students this signed-in person may see. Active only, newest names first.
 *
 * Falls back to the on-device roster when the request cannot reach the server.
 * That fallback is what makes offline logging reachable at all — see the long
 * note in src/lib/rosterCache.ts for why this one list is cached when no other
 * student data is.
 */
export async function fetchStudents(): Promise<StudentRow[]> {
  // Reads localStorage, not the network, so it still answers offline.
  const { data: sessionData } = await supabase.auth.getSession()
  const userId = sessionData.session?.user.id ?? null
  const cached = userId ? readCachedRoster(userId) : null

  const load = async () => {
    const { data, error } = await supabase
      .from('students')
      .select(
        'id, first_name, last_name, display_name, year_level, external_ref, is_active',
      )
      .eq('is_active', true)
      .order('first_name')

    if (error) throw new Error(error.message)

    const students = data ?? []
    if (userId) cacheRoster(userId, students)
    return students
  }

  // Nothing on the device to show, so there is nothing better than waiting for
  // the real answer and letting the error state explain itself.
  if (!cached) return load()
  return raceAgainstCache(load, cached)
}

/**
 * Answer from the device if the server is taking too long.
 *
 * WHY A RACE AND NOT A FALLBACK. A failed request does not fail quickly.
 * supabase-js refreshes the auth token before each call and retries that
 * refresh with backoff, so offline these spent about seven seconds losing
 * before the cache was consulted at all — a correct fallback arriving far too
 * late to be worth having.
 *
 * A second and a half, because a class list changes a few times a year.
 * Showing a slightly stale one costs nothing and the next successful load
 * replaces it. Nothing else in the product is cached, so nothing else races.
 *
 * A permission refusal is NOT answered from the cache. Showing a class to
 * someone whose verification has just been withdrawn is precisely what db/013
 * exists to prevent, so only a network failure falls back.
 */
function raceAgainstCache<T>(load: () => Promise<T>, cached: T): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    let settled = false
    const timer = setTimeout(() => {
      if (settled) return
      settled = true
      resolve(cached)
    }, 1500)

    void load().then(
      (fresh) => {
        clearTimeout(timer)
        if (settled) return
        settled = true
        resolve(fresh)
      },
      (error: unknown) => {
        clearTimeout(timer)
        if (settled) return
        settled = true
        if (isOfflineFailure(error)) resolve(cached)
        else reject(error instanceof Error ? error : new Error(String(error)))
      },
    )
  })
}

export type ClassroomStats = {
  totalStudents: number
  logsLast24h: number
  /**
   * Flagged AND not yet acknowledged — the ones that are actually waiting.
   *
   * This used to be every log ever flagged, under a tile reading "Needs
   * review". Measured on real data: 9 flagged, 6 already acknowledged by an
   * administrator, 3 genuinely open. The teacher was being told six things
   * needed reviewing that did not, forever, because nothing ever decremented
   * it. `safeguarding_acknowledged_at` has existed since db/010 for exactly
   * this question and was never asked.
   */
  flaggedOpen: number
  /** Flagged at any point, acknowledged or not. Context, not a to-do. */
  flaggedEver: number
}

/**
 * The three tiles at the top of the Classroom Overview.
 *
 * `head: true, count: 'exact'` asks Postgres for a count and no rows at all —
 * we want the number 24, not 24 student records we then measure the length of.
 * On a real school roster that difference matters.
 */
export async function fetchClassroomStats(): Promise<ClassroomStats> {
  const since = new Date(Date.now() - 24 * 60 * 60 * 1000).toISOString()

  const [students, logs, flaggedEver, flaggedOpen] = await Promise.all([
    supabase
      .from('students')
      .select('id', { count: 'exact', head: true })
      .eq('is_active', true),
    supabase
      .from('behaviour_logs')
      .select('id', { count: 'exact', head: true })
      .gte('occurred_at', since),
    supabase
      .from('behaviour_logs')
      .select('id', { count: 'exact', head: true })
      .eq('is_risk_flagged', true),
    // The one that answers the question the tile actually asks.
    supabase
      .from('behaviour_logs')
      .select('id', { count: 'exact', head: true })
      .eq('is_risk_flagged', true)
      .is('safeguarding_acknowledged_at', null),
  ])

  const firstError =
    students.error ?? logs.error ?? flaggedEver.error ?? flaggedOpen.error
  if (firstError) throw new Error(firstError.message)

  return {
    totalStudents: students.count ?? 0,
    logsLast24h: logs.count ?? 0,
    flaggedOpen: flaggedOpen.count ?? 0,
    flaggedEver: flaggedEver.count ?? 0,
  }
}

