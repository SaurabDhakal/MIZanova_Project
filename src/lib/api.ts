export type PersonRow = {
  id: string
  full_name: string | null
  email: string | null
  role: Role
  is_verified: boolean
  /** Children they guard at this school. Empty for staff. */
  children: { id: string; display_name: string; relationship: string }[]
  /** Students assigned to them. Empty for parents. */
  caseload: { id: string; display_name: string; assignment: string }[]
}

/**
 * Everyone at ONE named school — the platform-admin drill-down.
 *
 * STAFF COME FROM MEMBERSHIPS, NOT FROM `profiles.school_id`. That column is
 * the school somebody is working in RIGHT NOW (db/039), so a specialist who
 * holds three memberships would appear at one school and be missing from the
 * other two. `memberships` is what they MAY be, which is the question a
 * platform admin is asking.
 *
 * Parents come from the children, as everywhere else.
 */
export async function fetchPeopleAtSchool(schoolId: string): Promise<PersonRow[]> {
  const [members, students, profiles] = await Promise.all([
    supabase
      .from('memberships')
      .select('profile_id, role')
      .eq('organisation_id', schoolId)
      .is('ended_at', null),
    supabase.from('students').select('id, display_name').eq('school_id', schoolId),
    supabase.from('profiles').select('id, full_name, email, role, is_verified'),
  ])

  const failed = [members, students, profiles].find((r) => r.error)
  if (failed?.error) throw new Error(failed.error.message)

  const studentIds = (students.data ?? []).map((s) => s.id)
  const nameOf = new Map(
    (students.data ?? []).map((s) => [s.id, s.display_name as string]),
  )

  const [guardianLinks, assignments] = await Promise.all([
    studentIds.length
      ? supabase
          .from('student_guardians')
          .select('student_id, profile_id, relationship')
          .in('student_id', studentIds)
      : Promise.resolve({ data: [], error: null }),
    studentIds.length
      ? supabase
          .from('student_educators')
          .select('student_id, profile_id, assignment')
          .in('student_id', studentIds)
      : Promise.resolve({ data: [], error: null }),
  ])

  const byId = new Map((profiles.data ?? []).map((p) => [p.id as string, p]))

  /** Staff by membership, then guardians of this school's children. */
  const ids = new Set<string>([
    ...(members.data ?? []).map((m) => m.profile_id as string),
    ...(guardianLinks.data ?? []).map((g) => g.profile_id as string),
  ])

  return [...ids]
    .map((id) => byId.get(id))
    .filter((p): p is NonNullable<typeof p> => Boolean(p))
    .map((person) => ({
      ...(person as Omit<PersonRow, 'children' | 'caseload'>),
      /*
       * THE ROLE THEY HOLD HERE, not the one they are currently acting as.
       * A specialist who happens to be logged in as a parent elsewhere is
       * still this school's specialist, and `profiles.role` would say
       * otherwise.
       */
      role:
        ((members.data ?? []).find((m) => m.profile_id === person.id)
          ?.role as Role) ?? (person.role as Role),
      children: (guardianLinks.data ?? [])
        .filter((link) => link.profile_id === person.id)
        .map((link) => ({
          id: link.student_id as string,
          display_name: nameOf.get(link.student_id as string) ?? 'A student',
          relationship: link.relationship as string,
        })),
      caseload: (assignments.data ?? [])
        .filter((row) => row.profile_id === person.id)
        .map((row) => ({
          id: row.student_id as string,
          display_name: nameOf.get(row.student_id as string) ?? 'A student',
          assignment: row.assignment as string,
        })),
    }))
    .sort((a, b) => (a.full_name ?? '').localeCompare(b.full_name ?? ''))
}

