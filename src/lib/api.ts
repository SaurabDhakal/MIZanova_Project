/**
 * Share a log with the child's guardians, or withdraw that.
 *
 * This is the switch that decides whether a parent ever sees this observation.
 * The database default is false and the guardian RLS policy requires it to be
 * true, so nothing reaches a parent unless a human deliberately does this.
 */
export async function setLogShared(
  logId: string,
  shared: boolean,
): Promise<void> {
  const { data, error } = await supabase
    .from('behaviour_logs')
    .update({ shared_with_parents: shared })
    .eq('id', logId)
    .select('id')

  if (error) throw new Error(error.message)
  // Also catches the FR14 admin lock: after acknowledgement the author's
  // update matches no rows, and without this it would look like it worked.
  assertChanged(data, 'The sharing change')
}

