/**
 * One page of the people at this school, searched BY THE DATABASE.
 *
 * WHAT IT REPLACED. The first version fetched everybody and let the screen
 * filter in the browser, which is correct only while "everybody" fits in one
 * response. PostgREST stops at a thousand rows without saying so, and a
 * six-hundred-student school has roughly eight hundred parents — so the page
 * would have rendered a subset, looked complete, and been wrong in the
 * direction nobody checks. That version is deleted rather than kept beside
 * this one: two ways to ask the same question is how they start disagreeing.
 *
 * THE EDUCATOR ROSTER IS DELIBERATELY NOT CONVERTED. A teacher sees only the
 * students assigned to them — thirty, not thirty thousand — and that list is
 * cached in localStorage so behaviour logging works offline. Server-side
 * search would break offline search to solve a problem that role does not
 * have. Scale is a property of the query, not of the codebase.
 *
 * THREE ROUND TRIPS, BOUNDED BY THE PAGE. The profiles page is fetched first,
 * then the links for exactly those people. Fetching links for everybody and
 * discarding most would put the unbounded query back in a different place.
 */
export async function fetchSchoolPeoplePage(options: {
  search: string
  group: 'all' | 'staff' | 'parents'
  page: number
}): Promise<Page<PersonRow>> {
  const roles =
    options.group === 'parents'
      ? ['parent']
      : options.group === 'staff'
        ? ['educator', 'specialist', 'school_admin']
        : ['educator', 'specialist', 'school_admin', 'parent']

  const from = options.page * PAGE_SIZE
  let query = supabase
    .from('profiles')
    .select('id, full_name, email, role, is_verified', { count: 'exact' })
    .in('role', roles)

  const term = safeSearchTerm(options.search)
  if (term) {
    query = query.or(`full_name.ilike.%${term}%,email.ilike.%${term}%`)
  }

  const { data, error, count } = await query
    .order('full_name')
    .range(from, from + PAGE_SIZE - 1)

  if (error) throw new Error(error.message)

  const people = data ?? []
  const ids = people.map((p) => p.id as string)

  if (ids.length === 0) {
    return toPage([], count, options.page, PAGE_SIZE)
  }

  const [guardianLinks, assignments] = await Promise.all([
    supabase
      .from('student_guardians')
      .select('student_id, profile_id, relationship')
      .in('profile_id', ids),
    supabase
      .from('student_educators')
      .select('student_id, profile_id, assignment')
      .in('profile_id', ids),
  ])

  if (guardianLinks.error) throw new Error(guardianLinks.error.message)
  if (assignments.error) throw new Error(assignments.error.message)

  const studentIds = [
    ...new Set([
      ...(guardianLinks.data ?? []).map((g) => g.student_id as string),
      ...(assignments.data ?? []).map((a) => a.student_id as string),
    ]),
  ]

  const students = studentIds.length
    ? await supabase.from('students').select('id, display_name').in('id', studentIds)
    : { data: [], error: null }

  if (students.error) throw new Error(students.error.message)

  const nameOf = new Map(
    (students.data ?? []).map((s) => [s.id as string, s.display_name as string]),
  )

  const rows: PersonRow[] = people.map((person) => ({
    ...(person as Omit<PersonRow, 'children' | 'caseload'>),
    children: (guardianLinks.data ?? [])
      .filter((link) => link.profile_id === person.id)
      .map((link) => ({
        id: link.student_id as string,
        display_name: nameOf.get(link.student_id as string) ?? 'A student',
        relationship: link.relationship as string,
      })),
    caseload: (assignments.data ?? [])
      .filter((row) => row.profile_id === person.id)
      .map((row) => ({
        id: row.student_id as string,
        display_name: nameOf.get(row.student_id as string) ?? 'A student',
        assignment: row.assignment as string,
      })),
  }))

  return toPage(rows, count, options.page, PAGE_SIZE)
}

export type ServiceStatus = 'ok' | 'degraded' | 'unhealthy' | 'unreachable'

/**
 * Is the service working, right now?
 *
 * ONLY THE OVERALL STATE CROSSES THIS BOUNDARY. `/api/health` also reports
 * which API keys are configured, which is operational detail about the inside
 * of the server and nobody's business on a public page. It is read here and
 * deliberately not returned.
 *
 * A failure to reach the server is a RESULT, not an error — "we could not ask"
 * is the answer a status page most needs to be able to give, and throwing would
 * make the screen render a generic error box instead of saying so.
 */
export async function fetchServiceStatus(): Promise<ServiceStatus> {
  try {
    const response = await fetch(`${API_URL}/api/health`)
    const body = await response.json().catch(() => null)
    const state = body?.status
    return state === 'ok' || state === 'degraded' || state === 'unhealthy'
      ? state
      : 'unreachable'
  } catch {
    return 'unreachable'
  }
}

