/**
 * Make a search term safe to put inside a PostgREST `or(...)` filter.
 *
 * NOT AN INJECTION GUARD IN THE SQL SENSE — PostgREST parameterises values, and
 * RLS decides what may be returned whatever is asked for. It is a GRAMMAR
 * guard: `or()` takes a comma-separated list of `column.op.value`, so a comma,
 * a full stop or a bracket typed into a search box is read as syntax rather
 * than as text. Somebody searching for "Smith, J." would get a 400 and a
 * screen that looks broken.
 *
 * `%` and `_` go too. They are ilike wildcards, and a person typing one means
 * the character, not "match anything".
 */
function safeSearchTerm(raw: string): string {
  return (
    raw
      .replace(/[,().*%_\\]/g, ' ')
      .replace(/\s+/g, ' ')
      /*
       * TRIMMED AFTER the substitution, not before, and this was wrong first.
       *
       * Stripping punctuation turns "Smith, J." into "Smith J " — with the
       * trailing space the pattern becomes `%Smith J %`, which demands a space
       * after the J and matches nobody. Probed before shipping: every search
       * containing a full stop, comma or bracket returned zero results and no
       * error, which is the worst way to be wrong. A trim at the start cannot
       * catch it because the space does not exist yet.
       */
      .trim()
      .slice(0, 100)
  )
}

