/**
 * Which working goals are serving an agreed plan, and under which concern.
 *
 * THE ANSWER TO "IF THERE IS AN IEP, WHAT DO GOALS MEAN?" — Saurab's question,
 * and a fair one, because the two looked like duplicates.
 *
 *   an IEP goal      what the school and the family AGREED, at a meeting, on a
 *                    date, frozen afterwards
 *   a working goal   the day-to-day version a teacher breaks into tickable
 *                    steps and changes whenever the child changes
 *
 * They are not the same thing and neither replaces the other. Working goals
 * stay independent — a child with no plan still needs goals, which is common —
 * and `iep_goals.goal_id` records the link where one exists. This reads that
 * link so a screen can say "this goal is how we are working on the plan"
 * instead of leaving somebody to infer it.
 *
 * Returns a map keyed by working-goal id. Absent means the goal belongs to
 * nobody's plan, which is a legitimate state and not a gap.
 */
export async function fetchGoalPlanLinks(
  studentId: string,
): Promise<Record<string, { area: string; planId: string }>> {
  const { data, error } = await supabase
    .from('iep_goals')
    .select('goal_id, area_of_concern, plan_id, iep_plans!inner(student_id)')
    .eq('iep_plans.student_id', studentId)
    .not('goal_id', 'is', null)

  if (error) throw new Error(error.message)

  const links: Record<string, { area: string; planId: string }> = {}
  for (const row of data ?? []) {
    if (row.goal_id) {
      links[row.goal_id] = {
        area: row.area_of_concern,
        planId: row.plan_id,
      }
    }
  }
  return links
}

