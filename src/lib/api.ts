// Consent (FR25)
// ---------------------------------------------------------------------------
// A consent is a RECORD, not a setting. Granting inserts a row; withdrawing
// stamps `revoked_at` on that row and leaves it in place, because "consent was
// given on 2 August and withdrawn on 14 September" is itself the fact the
// Australian Privacy Principles require you to be able to prove. Nothing here
// ever deletes.

export type ConsentType =
  | 'data_processing'
  | 'ai_strategy_generation'
  | 'parent_portal_access'
  | 'specialist_referral'
  | 'photo_media'

export type ConsentRow = {
  id: string
  student_id: string
  consent_type: ConsentType
  granted_at: string
  revoked_at: string | null
  /** Which version of the privacy notice they were shown. */
  policy_version: string
  notes: string | null
  granted_by: string | null
}

/**
 * The version of the privacy notice currently shown to guardians.
 *
 * Stamped onto every consent as it is given. When the wording changes this
 * must change with it, otherwise the record claims someone agreed to text they
 * were never shown.
 */
export const PRIVACY_NOTICE_VERSION = 'v1'

/** Full consent history for a student, newest first. Revoked rows included. */
export async function fetchConsents(studentId: string): Promise<ConsentRow[]> {
  const { data, error } = await supabase
    .from('consents')
    .select(
      'id, student_id, consent_type, granted_at, revoked_at, policy_version, notes, granted_by',
    )
    .eq('student_id', studentId)
    .order('granted_at', { ascending: false })

  if (error) throw new Error(error.message)
  return (data ?? []) as ConsentRow[]
}

/**
 * Every consent row for every student the caller may see.
 *
 * No school filter and no student filter, on purpose: the `consents_select`
 * policy already returns only rows for students this person can view, so a
 * school admin gets their school and nobody else's. Adding a filter here would
 * create a second place to get it wrong and make it look as though the UI is
 * what protects the data.
 */
export async function fetchAllConsents(): Promise<ConsentRow[]> {
  const { data, error } = await supabase
    .from('consents')
    .select(
      'id, student_id, consent_type, granted_at, revoked_at, policy_version, notes, granted_by',
    )
    .order('granted_at', { ascending: false })

  if (error) throw new Error(error.message)
  return (data ?? []) as ConsentRow[]
}

/**
 * Give consent.
 *
 * The database has a unique index allowing only one un-revoked consent of each
 * type per student, so a double-click cannot create two contradictory live
 * records. That collision (23505) is reported plainly rather than swallowed —
 * if the button appears to do nothing, the person pressing it deserves to know
 * why.
 */
export async function grantConsent(input: {
  studentId: string
  consentType: ConsentType
  notes?: string
}): Promise<void> {
  const { data: user } = await supabase.auth.getUser()
  const grantedBy = user.user?.id
  if (!grantedBy) throw new Error('You are not signed in.')

  const { error } = await supabase.from('consents').insert({
    student_id: input.studentId,
    consent_type: input.consentType,
    granted_by: grantedBy,
    policy_version: PRIVACY_NOTICE_VERSION,
    notes: input.notes?.trim() ? input.notes.trim() : null,
  })

  if (error) {
    if (error.code === '23505') {
      throw new Error(
        'This consent is already active for this student. Reload the page to see the current state.',
      )
    }
    throw new Error(error.message)
  }
}

/**
 * Withdraw consent. Stamps the existing row; never deletes it.
 *
 * THE TIMESTAMP COMES FROM THE DATABASE, NOT FROM HERE. This used to send
 * `new Date().toISOString()`, which meant a laptop running a second slow
 * produced a `revoked_at` earlier than the `granted_at` the server had just
 * written — and db/002 correctly refuses that as nonsense. Withdrawing a
 * consent granted moments earlier failed with a raw constraint error, on the
 * one screen where a parent exercises a privacy right. See db/021.
 */
export async function revokeConsent(consentId: string): Promise<void> {
  const { data, error } = await supabase.rpc('revoke_consent', {
    p_consent_id: consentId,
  })

  if (error) throw new Error(error.message)

  // False means already withdrawn, or not this person's to withdraw. The
  // function cannot tell those apart and neither should the message.
  if (data !== true) {
    throw new Error(
      'That consent was not withdrawn. It may already have been withdrawn, or your account may not have permission for this record. Reload the page to see the current state.',
    )
  }
}

